import os
import logging
from google import genai

logger = logging.getLogger(__name__)

class GeminiProcessor:
    def __init__(self):
        self.api_key = os.environ.get("GEMINI_API_KEY")
        if not self.api_key:
            logger.warning("GEMINI_API_KEY не задан, Gemini-обработка отключена")
            self.enabled = False
            return
        self.client = genai.Client(api_key=self.api_key)
        self.enabled = True
        self.model = os.environ.get("GEMINI_MODEL", "gemini-2.0-flash")
        self.temperature = float(os.environ.get("GEMINI_TEMPERATURE", "0.85"))
        logger.info(f"GeminiProcessor инициализирован. Модель: {self.model}, температура: {self.temperature}")

    def process(self, text: str, style: str = "neutral") -> str:
        """
        Отправляет текст в Gemini для перефразирования с сохранением смысла.
        """
        if not self.enabled or len(text) < 100:
            return text

        prompt = self._build_prompt(text, style)
        try:
            response = self.client.models.generate_content(
                model=self.model,
                contents=prompt,
                config={
                    "temperature": self.temperature,
                    "max_output_tokens": len(text) * 2,
                }
            )
            result = response.text
            logger.info(f"Gemini обработал {len(text)} символов -> {len(result)} символов")
            return result
        except Exception as e:
            logger.error(f"Ошибка Gemini: {e}")
            return text

    def _build_prompt(self, text: str, style: str) -> str:
        # Базовые инструкции (общие для всех стилей)
        base_instructions = (
            "Ты — редактор художественных текстов. Твоя задача — переписать следующий текст так, "
            "чтобы он звучал максимально естественно, живо и по-человечески.\n\n"
            "Следуй этим правилам:\n"
            "1. Сохрани ВСЕХ персонажей, их имена, диалоги и ключевые события. Ничего не выдумывай, не добавляй и не убирай детали.\n"
            "2. ИЗБЕГАЙ канцеляризмов и официальных оборотов:\n"
            "   - 'в связи с тем, что' → 'потому что' или 'из-за того, что'\n"
            "   - 'осуществлять' → 'делать' или 'выполнять'\n"
            "   - 'в соответствии с' → 'по' или 'согласно'\n"
            "   - 'на основании' → 'по' или 'исходя из'\n"
            "   - 'является' → 'есть' (или убери вовсе)\n"
            "   - 'предпринимать' → 'делать' или 'браться'\n"
            "   - 'вносить изменения' → 'менять' или 'править'\n"
            "3. УБЕРИ маркеры ИИ: 'стоит отметить', 'следует подчеркнуть', 'важно понимать', 'необходимо учитывать', "
            "'обратите внимание', 'в целом', 'следует сказать', 'стоит заметить', 'несомненно', 'безусловно', "
            "'как уже упоминалось', 'как было сказано ранее', 'в данном контексте', 'следует признать', 'важно отметить'.\n"
            "4. Добавь лёгкую разговорность: используй частицы ('же', 'ведь', 'бы'), вводные слова ('впрочем', 'кстати', 'разумеется'), "
            "междометия ('ну', 'ой', 'ах', 'вот'), но НЕ переусердствуй — они должны звучать естественно, а не как вставки.\n"
            "5. Сделай предложения разной длины: чередуй короткие (3-5 слов) и длинные (10-15 слов).\n"
            "6. Используй активные глаголы (действие) вместо пассивных конструкций.\n"
            "7. Добавляй конкретные детали, где это уместно (цвета, звуки, ощущения, жесты), чтобы текст стал более живым.\n"
            "8. Сохрани атмосферу и тон оригинала (если текст мрачный — не делай его весёлым).\n"
            "9. НЕ меняй смысл и НЕ добавляй новую информацию.\n"
            "10. Верни ТОЛЬКО переписанный текст, без лишних комментариев, без предисловий и пояснений.\n\n"
        )

        # Примеры хороших замен (для вдохновения)
        examples = (
            "Примеры улучшений:\n"
            "- Было: 'Он принял решение отправиться в путь, несмотря на предупреждения коллег.'\n"
            "  Стало: 'Он всё-таки решил идти, хотя коллеги его предупреждали.'\n"
            "- Было: 'Необходимо учитывать тот факт, что ситуация может измениться.'\n"
            "  Стало: 'Но ситуация могла измениться в любой момент.'\n"
            "- Было: 'Она начала осуществлять свои планы по реорганизации лаборатории.'\n"
            "  Стало: 'Она взялась за реорганизацию лаборатории.'\n\n"
        )

        # Специфичные для стиля дополнения
        style_prompts = {
            "neutral": (
                "Стиль: универсальный. Сделай текст естественным и лёгким для чтения. "
                "Он должен звучать как рассказ хорошего автора, но без излишней вычурности. "
                "Сохрани ритм и атмосферу.\n\n"
            ),
            "dynamic_scifi": (
                "Стиль: научная фантастика. Сделай текст более динамичным, напряжённым и образным. "
                "Используй короткие предложения для экшена, добавляй эмоциональные восклицания и "
                "метафоры. Сохрани технолексику, но сделай её более естественной для персонажей.\n\n"
            ),
            "literary": (
                "Стиль: литературная проза. Сделай текст более глубоким, образным и атмосферным. "
                "Добавь больше описаний, внутренних монологов, метафор. Сохрани плавность и "
                "красоту языка, но избегай излишней высокопарности.\n\n"
            ),
        }

        # Полный промпт = базовые инструкции + примеры + стилевые дополнения + текст
        full_prompt = base_instructions + examples + style_prompts.get(style, style_prompts["neutral"]) + text
        return full_prompt
