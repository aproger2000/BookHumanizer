# ===== ГЕНЕРАЦИЯ КОМБИНАЦИЙ ДЛЯ АВТОМАТИЧЕСКОГО ПОИСКА =====
def gen_vals(start, stop, step):
    """Генерирует список значений от start до stop с шагом step"""
    vals = []
    cur = start
    while cur <= stop + 0.001:
        vals.append(round(cur, 2))
        cur += step
    return vals

